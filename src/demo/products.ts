import type { ProductListItem } from "@/types/agrishopping";
import { DEMO_MEDIA } from "./media";
import { demoProviderById } from "./providers";

const CREATED_AT = "2026-01-15T09:00:00.000Z";

export type DemoProduct = ProductListItem & { isDemo: true };

function seller(providerId: string) {
  const provider = demoProviderById(providerId);
  if (!provider) throw new Error(`Demo provider em falta: ${providerId}`);
  return provider;
}

function product(
  input: Omit<DemoProduct, "isDemo" | "seller_name" | "seller_slug" | "seller_rating" | "seller_verified" | "currency" | "created_at"> & {
    seller_id: string;
  }
): DemoProduct {
  const provider = seller(input.seller_id);
  return {
    ...input,
    isDemo: true,
    seller_name: provider.business_name,
    seller_slug: provider.slug,
    seller_rating: provider.rating,
    seller_verified: true,
    currency: "AOA",
    created_at: CREATED_AT,
  };
}

